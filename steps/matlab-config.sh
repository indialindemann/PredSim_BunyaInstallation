# Write the runtime env file ($PREFIX/env.sh) that PredSim's
# linux/run_predsim.sh sources. Everything a run needs is in this one file.

step_main() {
    local rel
    rel="$(grep -oE '<release>R[0-9]{4}[ab]' "$MATLAB_ROOT/VersionInfo.xml" 2>/dev/null | sed 's/<release>//')"
    [[ -n "$rel" ]] || rel="$(basename "$MATLAB_ROOT")"
    local jni; jni="$(dirname "$(find "$OPENSIM_PREFIX/opensim" -name libosimJavaJNI.so | head -1)")"
    [[ -d "$jni" ]] || die "libosimJavaJNI.so not found under $OPENSIM_PREFIX/opensim (run the opensim step)"

    cat > "$PREFIX/env.sh" <<EOF
# PredSim runtime environment, generated by PredSim_BunyaInstallation/predsim-install.sh
# stack: $STACK_ID   ($(date -I))
export PREDSIM_STACK="$STACK_ID"
export PREDSIM_SITE="$SITE"
export PREDSIM_PREFIX="$PREFIX"
export PREDSIM_CASADI_DIR="$PREFIX/casadi"
export OPENSIM_HOME="$OPENSIM_PREFIX/opensim"
export EBROOTOPENSIMAD="$PREFIX/opensimad/linux"
export PREDSIM_MATLAB_RELEASE="$rel"
# run_predsim.sh keeps ~/.matlab/$rel/javalibrarypath.txt pointing here
export PREDSIM_JAVA_LIBRARY_PATH="$jni"
export PREDSIM_SBATCH_ARGS="$PREDSIM_SBATCH_ARGS"
# --- site runtime setup (modules etc.); must come before the venv PATH below,
#     or a site python module would shadow the venv's python
$(site_runtime_env)
# venv first: opensimAD runs 'python genF.py' (needs casadi) and 'cmake' at run time
export VIRTUAL_ENV="$PREFIX/python"
export PATH="$PREFIX/python/bin:\$PATH"
# CasADi threads come from S.solver.N_threads; keep BLAS/OpenMP pools from
# oversubscribing the cores on top of that.
export OMP_NUM_THREADS="\${OMP_NUM_THREADS:-1}"
export OPENBLAS_NUM_THREADS="\${OPENBLAS_NUM_THREADS:-1}"
EOF
    if [[ -f "$PREFIX/hsl/lib/libhsl.so" ]]; then
        cat >> "$PREFIX/env.sh" <<EOF
# CoinHSL (--hsl): PredSim's solve_NLPSOL uses Ipopt linear_solver=ma97 when
# this file exists. PREDSIM_HSL_LIB= (set but empty) falls back to MUMPS.
# MA97 threads: OMP_NUM_THREADS.
export PREDSIM_HSL_LIB="\${PREDSIM_HSL_LIB-$PREFIX/hsl/lib/libhsl.so}"
EOF
    fi
    # the venv's python must win (it has casadi for opensimAD's genF.py)
    ( source "$PREFIX/env.sh" >/dev/null 2>&1; [[ "$(command -v python)" == "$PREFIX/python/bin/python" ]] ) \
        || die "env.sh: 'python' does not resolve to $PREFIX/python/bin/python"
    log "wrote $PREFIX/env.sh"
    cat "$PREFIX/env.sh"
}
